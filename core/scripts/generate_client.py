# Method generation
method_codes = []
seen_names = {}

# Sort routes to keep order stable
routes.sort(key=lambda x: x['path'])

NAME_MAPPING = {
    '/api/company/<company_id>/cameras/discover': 'discoverCameras',
    '/api/company/<company_id>/cameras/manual-test': 'testCamera',
    '/api/company/<company_id>/cameras/batch-provision': 'batchProvision',
    '/api/company/<company_id>/dvr/add': 'addDVR',
    '/api/company/<company_id>/dvr/<dvr_id>/discover': 'discoverDVRChannels',
    '/api/company/<company_id>/cameras/<camera_id>/stream-status': 'getStreamDiagnostics',
    '/api/company/<company_id>/start-detection': 'startDetection',
    '/api/company/<company_id>/stop-detection': 'stopDetection',
    '/api/company/<company_id>/active-detections': 'getActiveDetections',
}

BODY_WRAPPERS = {
    'startDetection': 'camera_id',
    'stopDetection': 'camera_id',
    'testCamera': 'camera_id',
    'discoverCameras': 'mode',
}

for route in routes:
    path = route['path']
    method = route['method']
    
    # Custom naming logic for better UX
    if path in NAME_MAPPING:
        clean_name = NAME_MAPPING[path]
    else:
        clean_name = to_camel_case(path)
        if method == 'POST' and not clean_name.startswith('post'):
            if clean_name.startswith('get'):
                clean_name = 'post' + clean_name[3:]
        
    # Handle duplicates
    full_name = f"{clean_name}_{method.lower()}" if seen_names.get(clean_name, 0) > 0 else clean_name
    seen_names[clean_name] = seen_names.get(clean_name, 0) + 1
    
    path_params = parse_path_params(path)
    clean_p = clean_flask_path(path)
    
    # Arg generation
    ts_args = list(path_params) # names with types
    
    has_body = method in ('POST', 'PUT', 'PATCH')
    if has_body:
        ts_args.append("params?: any")
    
    final_args_str = ", ".join(ts_args)

    method_code = f"  public async {full_name}({final_args_str}): Promise<any> {{\n"
    
    if has_body and clean_name in BODY_WRAPPERS:
        wrapper_key = BODY_WRAPPERS[clean_name]
        method_code += f"    const body = (params !== undefined && (typeof params !== 'object' || params === null)) ? {{ {wrapper_key}: params }} : params;\n"
        method_code += f"    return this.call(\"{method}\", `{clean_p}`, body);\n"
    else:
        method_code += f"    return this.call(\"{method}\", `{clean_p}`{', params' if has_body else ''});\n"
    
    method_code += "  }\n"
    
    method_codes.append(method_code)

# Write to file
with open(FRONTEND_PATH, "w", encoding="utf-8") as f:
    f.write(HEADER)
    f.write("\n".join(method_codes))
    f.write(FOOTER)

print(f"✅ Successfully generated {len(method_codes)} methods in {FRONTEND_PATH}")
