def to_camel_case(text):
    # Remove slash prefixes
    text = text.strip('/').replace('/', '_').replace('-', '_')
    # Remove params like <company_id>
    text = re.sub(r'<[^>]+>', '', text)
    # Convert under_score to camelCase
    components = [x for x in text.split('_') if x]
    if not components: return "index"
    return components[0].lower() + "".join(x.title() for x in components[1:])

def parse_path_params(path):
    # Flask format <param> or <type:param>
    params = re.findall(r'<([^>]+)>', path)
    ts_params = []
    for p in params:
        name = p.split(':')[-1]
        ts_params.append(f"{name}: string")
    return ts_params

def clean_flask_path(path):
    # Convert Flask <param> to TS ${param}
    def replacer(match):
        param = match.group(1).split(':')[-1]
        return f"${{{param}}}"
    return re.sub(r'<([^>]+)>', replacer, path)

# Collect routes
routes = []
for rule in app.url_map.iter_rules():
    # Skip static routes and core internal routes
    if rule.endpoint == 'static' or rule.rule.startswith('/static'):
        continue
    
    methods = [m for m in rule.methods if m not in ('OPTIONS', 'HEAD')]
    if not methods: continue
    
    for method in methods:
        routes.append({
            'path': rule.rule,
            'method': method,
            'endpoint': rule.endpoint
        })

